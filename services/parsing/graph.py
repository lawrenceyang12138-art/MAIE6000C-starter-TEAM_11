"""Read a version's candidate relations, and record human decisions on them.

Two properties matter here.

**Bounded reads.** The schedule asks for a bounded relation read, not a graph
walk. The limit is enforced in code rather than left to callers, so a document
that produced fifty candidates cannot turn into a fifty-node graph by accident.

**Append-only review with a revision guard.** A decision never overwrites a
previous one; it is appended with the next revision number, so the history of
who decided what, and when, survives. The caller passes the revision it
believes is current, and the write is refused if that is no longer true. Two
people reviewing the same relation at the same time therefore produce a
visible conflict instead of one silently discarding the other's decision.

Human decisions are the one thing in this system that is never regenerated by
reprocessing, so they are stored to outlive everything derived.
"""

from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from services.common.models import (
    Entity,
    Relationship,
    RelationshipEvidence,
    Review,
    ReviewDecision,
    SourceChunk,
)

# A read is bounded in code, not by convention.
MAX_RELATIONSHIPS = 20

VALID_DECISIONS = {
    ReviewDecision.CONFIRMED.value,
    ReviewDecision.CORRECTED.value,
    ReviewDecision.REJECTED.value,
}

REASON_REVIEW_CONFLICT = "review_conflict"
REASON_INVALID_DECISION = "invalid_decision"
REASON_RELATIONSHIP_NOT_FOUND = "relationship_not_found"
REASON_CORRECTION_WITHOUT_TARGET = "correction_without_target"
REASON_CORRECTION_TARGET_NOT_ALLOWED = "correction_target_not_allowed"
REASON_CORRECTED_ENTITY_NOT_FOUND = "corrected_entity_not_found"


class ReviewRefused(Exception):
    """A decision was not recorded, with a reason the caller can show."""

    def __init__(self, reason_code: str, message: str) -> None:
        super().__init__(message)
        self.reason_code = reason_code
        self.message = message


@dataclass(frozen=True)
class RelationshipView:
    """One candidate relation, ready to display next to its evidence."""

    relationship_id: str
    entity_type: str
    label: str
    relation_type: str
    kind: str
    origin: str
    producer_revision: str
    page_number: int | None
    quote: str
    # True when the passage that justified this relation is gone - for
    # instance because the version was re-processed and the chunk it cited was
    # replaced. A relation without its evidence is not something to show as if
    # it were checkable, so the caller can tell the difference.
    evidence_missing: bool
    # The latest human decision, or None while the candidate is unreviewed.
    decision: str | None
    # What a "corrected" decision points to instead, when one is recorded.
    corrected_entity_id: str | None
    # The revision a caller must quote back when reviewing.
    decision_revision: int


def _latest_review(db: Session, relationship_id: str) -> Review | None:
    return (
        db.execute(
            select(Review)
            .where(Review.relationship_id == relationship_id)
            .order_by(Review.decision_revision.desc())
            .limit(1)
        )
        .scalars()
        .first()
    )


def effective_decision(db: Session, relationship_id: str) -> tuple[str | None, int]:
    """Return (latest decision, latest revision). No reviews means revision 0."""
    latest = _latest_review(db, relationship_id)
    if latest is None:
        return None, 0
    return latest.decision, latest.decision_revision


def read_relationships(
    db: Session, version_id: str, limit: int = MAX_RELATIONSHIPS
) -> list[RelationshipView]:
    """Return at most ``limit`` candidate relations for one version.

    Each view carries its first evidence quote and its page, so the caller can
    show why the candidate exists rather than only that it does.
    """
    bounded = max(0, min(limit, MAX_RELATIONSHIPS))
    if bounded == 0:
        return []

    rows = db.execute(
        select(Relationship, Entity)
        .join(Entity, Relationship.object_entity_id == Entity.id)
        .where(Relationship.source_version_id == version_id)
        .order_by(Entity.entity_type, Entity.display_label)
        .limit(bounded)
    ).all()

    views: list[RelationshipView] = []
    for relationship, entity in rows:
        evidence = db.execute(
            select(RelationshipEvidence, SourceChunk)
            .join(SourceChunk, RelationshipEvidence.chunk_id == SourceChunk.id)
            .where(RelationshipEvidence.relationship_id == relationship.id)
            .order_by(RelationshipEvidence.start_offset)
            .limit(1)
        ).first()

        latest = _latest_review(db, relationship.id)
        views.append(
            RelationshipView(
                relationship_id=relationship.id,
                entity_type=entity.entity_type,
                label=entity.display_label,
                relation_type=relationship.relation_type,
                kind=relationship.kind,
                origin=relationship.origin,
                producer_revision=relationship.producer_revision,
                page_number=evidence[1].page_number if evidence else None,
                quote=evidence[0].quote if evidence else "",
                evidence_missing=evidence is None,
                decision=latest.decision if latest else None,
                corrected_entity_id=latest.corrected_entity_id if latest else None,
                decision_revision=latest.decision_revision if latest else 0,
            )
        )
    return views


def record_review(
    db: Session,
    relationship_id: str,
    decision: str,
    expected_revision: int,
    reason: str | None = None,
    actor: str | None = None,
    corrected_entity_id: str | None = None,
) -> int:
    """Append a decision and return the new revision number.

    ``expected_revision`` is what the caller last saw. If someone else has
    reviewed the relation since, this raises rather than overwriting them.

    A ``corrected`` decision has to name the entity it points to instead. That
    is the whole difference between "this is wrong" and "this is what it should
    be" — without the replacement, a correction is only a rejection with a
    different word on it. Confirmations and rejections must not carry one.
    """
    if decision not in VALID_DECISIONS:
        raise ReviewRefused(
            REASON_INVALID_DECISION,
            f"decision must be one of {sorted(VALID_DECISIONS)}",
        )

    relationship = db.get(Relationship, relationship_id)
    if relationship is None:
        raise ReviewRefused(
            REASON_RELATIONSHIP_NOT_FOUND, "No such relationship"
        )

    is_correction = decision == ReviewDecision.CORRECTED.value
    if is_correction and corrected_entity_id is None:
        raise ReviewRefused(
            REASON_CORRECTION_WITHOUT_TARGET,
            "a corrected decision must name the entity it points to",
        )
    if not is_correction and corrected_entity_id is not None:
        raise ReviewRefused(
            REASON_CORRECTION_TARGET_NOT_ALLOWED,
            f"only a corrected decision may name a replacement, not {decision}",
        )
    if corrected_entity_id is not None and db.get(Entity, corrected_entity_id) is None:
        raise ReviewRefused(
            REASON_CORRECTED_ENTITY_NOT_FOUND, "No such corrected entity"
        )

    _, current_revision = effective_decision(db, relationship_id)
    if expected_revision != current_revision:
        raise ReviewRefused(
            REASON_REVIEW_CONFLICT,
            f"expected revision {expected_revision} but the current revision is "
            f"{current_revision}",
        )

    review = Review(
        relationship_id=relationship_id,
        decision_revision=current_revision + 1,
        decision=decision,
        corrected_entity_id=corrected_entity_id,
        reason=reason,
        actor=actor,
    )
    db.add(review)
    try:
        db.commit()
    except IntegrityError as exc:
        # Two reviewers who submit at the same instant both read the same
        # expected revision, so both pass the guard above and both try to
        # write the next one. The unique constraint on
        # (relationship_id, decision_revision) is what actually stops the
        # second write; without this branch that arrives as a database error
        # rather than the conflict the caller is written to expect.
        db.rollback()
        raise ReviewRefused(
            REASON_REVIEW_CONFLICT,
            "another decision reached this revision first; re-read and retry",
        ) from exc
    return review.decision_revision
